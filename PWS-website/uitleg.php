    <p>In werkruimtes en vooral in scholen verblijven vaak veel mensen gedurende langere tijd in dezelfde ruimte.
  <br> Dit heeft directe invloed op de luchtkwaliteit. Een belangrijke indicator voor deze luchtkwaliteit is het CO2-gehalte (koolstofdioxide) in de lucht. 
  <br>In dit theoretisch kader wordt uitgelegd wat CO2 is, welke minimum- en maximumwaarden gelden, 
  <br>waarom een hoog CO2-gehalte schadelijk is en waarom CO2-monitoring en automatische ventilatie in scholen belangrijk zijn.</p>
