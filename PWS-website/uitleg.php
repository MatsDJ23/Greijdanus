      <p>Voor binnenruimtes worden de volgende richtlijnen gehanteerd: <br>
         <br>- 400–420 ppm: buitenlucht en theoretisch minimum voor binnenruimtes
         <br>- ≤800 ppm: goede luchtkwaliteit, ideaal voor leer- en werkomgevingen
         <br>- 800–1000 ppm: acceptabel, maar niet optimaal
